bool AMSUnitBase::CanBeLockedOn() const
{
	// 死亡済み(State.Dead)は候補から除外(P0-4契約)。陣営判定はUMSTeamStatics::CanLockOn側。
	return AbilitySystemComponent && !AbilitySystemComponent->HasMatchingGameplayTag(MSTags::State_Dead);
}

FVector AMSUnitBase::GetLockOnAimPoint() const
{
	if (HitReactionComponent && HitReactionComponent->GetPhase()!=EMSHitReactionPhase::None && MechRigComponent)
		if (const USceneComponent* Torso=MechRigComponent->GetJoint(TEXT("Torso"))) return Torso->GetComponentLocation();
	// 機体胸元 = カプセル底(接地点)から AimPointHeightAboveBase 上方。
	// LOS起点をカメラにしない(ガードレールB-5)。
	const float HalfHeight = GetCapsuleComponent()->GetScaledCapsuleHalfHeight();
	return GetActorLocation() + FVector(0.0f, 0.0f, AimPointHeightAboveBase - HalfHeight);
}

void AMSUnitBase::BeginPlay()
{
	Super::BeginPlay();
	if (UMSCharacterMovementComponent* Movement = Cast<UMSCharacterMovementComponent>(GetCharacterMovement()))
	{
		Movement->RefreshZeroGravityModeFromWorld();
	}
	if (MechRigComponent)
	{
		MechRigComponent->ApplyAppearance(TeamId.GetId(), false, 0);
	}
	if (UMSUnitRegistrySubsystem* Registry = GetWorld()->GetSubsystem<UMSUnitRegistrySubsystem>()) Registry->RegisterUnit(this);
}

void AMSUnitBase::EndPlay(const EEndPlayReason::Type EndPlayReason)
{
	if (UWorld* World = GetWorld())
	{
		if (UMSUnitRegistrySubsystem* Registry = World->GetSubsystem<UMSUnitRegistrySubsystem>()) Registry->UnregisterUnit(this);
	}
	Super::EndPlay(EndPlayReason);
}

void AMSUnitBase::PostInitializeComponents()
{
	Super::PostInitializeComponents();
	if (MechRigComponent)
	{
		MechRigComponent->ApplyAppearance(TeamId.GetId(), false, 0);
	}

	// BOT・未Possess配置(検証マップ直置き等)でもASCを有効化する。
	// プレイヤーはPossessedByでも再実行される(多重呼び出し安全)。
	InitAbilityActorInfoIfNeeded();

	// エディタ設定済みの既定機体データで初期化(実戦のDeploy/リスポーンはInitializeUnitを再度通る)
	if (MobileSuitData)
	{
		InitializeUnit(MobileSuitData);
	}
}

void AMSUnitBase::PossessedBy(AController* NewController)
{
	Super::PossessedBy(NewController);

	// Possessタイミングでの再初期化(Owner=Avatar=自分のため実質冪等だが、GAS慣例に従い明示)
	InitAbilityActorInfoIfNeeded();
}

