const FName AMSUnitBase::HeadHitboxComponentName(TEXT("HeadHitbox"));

namespace
{
	// コリジョンプロファイル名(Config/DefaultEngine.ini のP0-5定義と一致させること)
	const FName Profile_MSPawnCapsule(TEXT("MSPawnCapsule"));
	const FName Profile_MSHitbox(TEXT("MSHitbox"));
	const FName Profile_MSNoCollision(TEXT("MSNoCollision"));
}

AMSUnitBase::AMSUnitBase(const FObjectInitializer& ObjectInitializer)
	: Super(ObjectInitializer)
{
	PrimaryActorTick.bCanEverTick = false;
	bReplicates = true;
	SetReplicateMovement(true);
	GetCapsuleComponent()->InitCapsuleSize(34.0f * MSGO::MSScale, 88.0f * MSGO::MSScale);

	// 当たり判定は機体カプセル+HeadHitboxのみで完結する(§3.4 不変条件)
	GetCapsuleComponent()->SetCollisionProfileName(Profile_MSPawnCapsule);
	GetMesh()->SetCollisionProfileName(Profile_MSNoCollision);

	// The inherited skeletal component remains only as an ACharacter implementation detail.
	// Visuals are generated by the runtime Cube rig, so it must never render a fallback asset.
	GetMesh()->SetVisibility(false);
	GetMesh()->SetHiddenInGame(true);

	// Combat is server-authoritative in multiplayer. Full mode is intentional while Owner=Avatar
	// remains the Pawn; it makes vital attributes and gameplay cues observable by both clients.
	AbilitySystemComponent = CreateDefaultSubobject<UAbilitySystemComponent>(TEXT("AbilitySystemComponent"));
	AbilitySystemComponent->SetIsReplicated(true);
	AbilitySystemComponent->SetReplicationMode(EGameplayEffectReplicationMode::Full);

	// Vital属性セット(P2-2)。Actorサブオブジェクトのため InitAbilityActorInfo でASCに自動登録される
	VitalSet = CreateDefaultSubobject<UMSAttributeSet_Vital>(TEXT("VitalSet"));

	// DP自然回復(P2-6。被弾後2.5s無被弾で40/s。VitalSetのLastDamageTimeを参照する軽量Tick)
	DownPointRegenComponent = CreateDefaultSubobject<UMSDownPointRegenComponent>(TEXT("DownPointRegen"));
	HitReactionComponent = CreateDefaultSubobject<UMSHitReactionComponent>(TEXT("HitReaction"));

	// Boost属性セット(P3-2)。消費0到達の強制OH遷移はセット側が担う
	BoostSet = CreateDefaultSubobject<UMSAttributeSet_Boost>(TEXT("BoostSet"));

	// ブースト消費/回復駆動(P3-2。Unity: HandleBoostState。レートはInitializeUnitで機体データから設定)
	BoostComponent = CreateDefaultSubobject<UMSBoostComponent>(TEXT("BoostComponent"));
	WeaponComponent = CreateDefaultSubobject<UMSWeaponComponent>(TEXT("WeaponComponent"));
	ShieldComponent = CreateDefaultSubobject<UMSShieldComponent>(TEXT("ShieldComponent"));
	MechRigComponent = CreateDefaultSubobject<UMSMechRigComponent>(TEXT("MechRigComponent"));
	MechAnimatorComponent = CreateDefaultSubobject<UMSMechAnimatorComponent>(TEXT("MechAnimatorComponent"));
	MeshVisualComponent = CreateDefaultSubobject<UMSMeshVisualComponent>(TEXT("MeshVisualComponent"));
	WeaponVisualComponent = CreateDefaultSubobject<UMSWeaponVisualComponent>(TEXT("WeaponVisualComponent"));

	// GE_InitStatsの既定実体はネイティブ定義(UGE_InitStats)。BPで差し替え可能(§1.4)
	InitStatsEffectClass = UGE_InitStats::StaticClass();

	// 頭部ヒットボックス(§3.3: WeaponTraceのみBlock、移動・カメラに一切干渉しない)。
	// アタッチ先ソケット・正確な位置はP2-5/P5-1で確定。暫定でカプセル上端相当に置く。
	HeadHitbox = CreateDefaultSubobject<USphereComponent>(HeadHitboxComponentName);
	HeadHitbox->SetupAttachment(GetCapsuleComponent());
	HeadHitbox->SetCollisionProfileName(Profile_MSHitbox);
	HeadHitbox->SetSphereRadius(20.0f * MSGO::MSScale);
	HeadHitbox->SetRelativeLocation(FVector(0.0f, 0.0f, GetCapsuleComponent()->GetUnscaledCapsuleHalfHeight()));
	HeadHitbox->SetCanEverAffectNavigation(false);
}

UAbilitySystemComponent* AMSUnitBase::GetAbilitySystemComponent() const
{
	return AbilitySystemComponent;
}

